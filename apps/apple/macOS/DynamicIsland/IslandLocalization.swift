/// Localized copy for the macOS Dynamic Island, aligned with `src/shared/locales/{en,zh-CN}/island.json`.
/// Self-contained inside the Dynamic Island module so it stays cleanly decoupled from shared localization files.
struct IslandStrings: Sendable, Equatable {
    let isChinese: Bool

    init(language: PrismLanguage) {
        switch language {
        case .zhHans:
            self.isChinese = true
        case .en:
            self.isChinese = false
        case .system:
            let preferred = Locale.preferredLanguages.first?.lowercased() ?? "en"
            self.isChinese = preferred.hasPrefix("zh")
        }
    }

    var localeIdentifier: String {
        isChinese ? "zh-CN" : "en"
    }

    func text(_ key: String, _ values: [String: String] = [:]) -> String {
        let table = isChinese ? Self.zhHans : Self.en
        var resolved = table[key] ?? Self.en[key] ?? key
        for (name, value) in values {
            resolved = resolved.replacingOccurrences(of: "{{\(name)}}", with: value)
        }
        return resolved
    }

    func counted(_ key: String, _ count: Int) -> String {
        let values = ["count": "\(count)"]
        let table = isChinese ? Self.zhHans : Self.en
        if !isChinese && count == 1, let one = table["\(key)_one"] {
            return one.replacingOccurrences(of: "{{count}}", with: "\(count)")
        }
        if let other = table["\(key)_other"] {
            return other.replacingOccurrences(of: "{{count}}", with: "\(count)")
        }
        return text(key, values)
    }

